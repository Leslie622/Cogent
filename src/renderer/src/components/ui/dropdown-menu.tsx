import * as React from "react"
import { Menu as MenuPrimitive } from "@base-ui/react/menu"
import { cva, type VariantProps } from "class-variance-authority"
import { cn } from "cn"
import { ChevronRightIcon, CheckIcon } from "lucide-react"

/**
 * 菜单尺寸档（2026-11-16 加 lg）：Content 下发 SizeContext，行/标签/分割线按
 * context 拼字面类 —— 不用 data-* 祖先变体（[[data-size=lg]_&]: 语法经隔离
 * 编译探针有效，但 vite 管线的 oxide 提取器对 TSX 源串里 [ 开头的候选实际
 * 不生成，产物缺失且 touch/清缓存均不恢复；字面条件类是百分百可靠的形态）。
 * size 不传 = 继承外层（React Context 沿 React 树传播、portal 不断 ——
 * SubContent 渲染走本组件且默认不传，子菜单面板自动跟随主面板放大）。
 */
const MenuSizeContext = React.createContext<"default" | "lg">("default")

function DropdownMenu({ ...props }: MenuPrimitive.Root.Props) {
  return <MenuPrimitive.Root data-slot="dropdown-menu" {...props} />
}

function DropdownMenuPortal({ ...props }: MenuPrimitive.Portal.Props) {
  return <MenuPrimitive.Portal data-slot="dropdown-menu-portal" {...props} />
}

function DropdownMenuTrigger({ ...props }: MenuPrimitive.Trigger.Props) {
  return <MenuPrimitive.Trigger data-slot="dropdown-menu-trigger" {...props} />
}

function DropdownMenuContent({
  align = "start",
  alignOffset = 0,
  side = "bottom",
  sideOffset = 4,
  size,
  className,
  ...props
}: MenuPrimitive.Popup.Props &
  Pick<
    MenuPrimitive.Positioner.Props,
    "align" | "alignOffset" | "side" | "sideOffset"
  > &
  VariantProps<typeof dropdownMenuContentVariants>) {
  const inherited = React.useContext(MenuSizeContext)
  const resolved = size ?? inherited
  return (
    <MenuSizeContext.Provider value={resolved}>
      <MenuPrimitive.Portal>
        <MenuPrimitive.Positioner
          className="isolate z-50 outline-none"
          align={align}
          alignOffset={alignOffset}
          side={side}
          sideOffset={sideOffset}
        >
          <MenuPrimitive.Popup
            data-slot="dropdown-menu-content"
            className={cn(dropdownMenuContentVariants({ size: resolved }), className)}
            {...props}
          />
        </MenuPrimitive.Positioner>
      </MenuPrimitive.Portal>
    </MenuSizeContext.Provider>
  )
}

const dropdownMenuContentVariants = cva(
  "z-50 max-h-(--available-height) w-(--anchor-width) min-w-32 origin-(--transform-origin) overflow-x-hidden overflow-y-auto rounded-lg bg-popover p-1 text-popover-foreground shadow-md ring-1 ring-foreground/10 duration-100 outline-none data-[side=bottom]:slide-in-from-top-2 data-[side=inline-end]:slide-in-from-left-2 data-[side=inline-start]:slide-in-from-right-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 data-open:animate-in data-open:fade-in-0 data-open:zoom-in-95 data-closed:animate-out data-closed:overflow-hidden data-closed:fade-out-0 data-closed:zoom-out-95",
  {
    variants: {
      size: {
        // lg = 放大档：面板放宽（rounded-xl + p-1.5），行/标签/分割线的 lg
        // 形态在各自原语按 MenuSizeContext 拼字面类
        default: "",
        lg: "rounded-xl p-1.5",
      },
    },
    defaultVariants: {
      size: "default",
    },
  }
)

function DropdownMenuGroup({ ...props }: MenuPrimitive.Group.Props) {
  return <MenuPrimitive.Group data-slot="dropdown-menu-group" {...props} />
}

function DropdownMenuLabel({
  className,
  inset,
  ...props
}: MenuPrimitive.GroupLabel.Props & {
  inset?: boolean
}) {
  const size = React.useContext(MenuSizeContext)
  return (
    <MenuPrimitive.GroupLabel
      data-slot="dropdown-menu-label"
      data-inset={inset}
      className={cn(
        "px-1.5 py-1 text-xs font-medium text-muted-foreground data-inset:pl-7",
        size === "lg" && "px-2 py-1.5",
        className
      )}
      {...props}
    />
  )
}

function DropdownMenuItem({
  className,
  inset,
  variant = "default",
  ...props
}: MenuPrimitive.Item.Props & {
  inset?: boolean
  variant?: "default" | "destructive" | "warning"
}) {
  const size = React.useContext(MenuSizeContext)
  return (
    <MenuPrimitive.Item
      data-slot="dropdown-menu-item"
      data-inset={inset}
      data-variant={variant}
      className={cn(
        // warning 变体（2026-11-11 加，照 destructive 同款模式）：focus 高亮态的
        // `**:text-accent-foreground` 会把所有后代强制染黑，子元素自定义色打不过
        // 它 —— 强调色必须在 item 层以变体声明并从通配染色中排除（权限菜单
        // 「完全访问」warning 琥珀 hover 变黑的修复）
        "group/dropdown-menu-item relative flex cursor-default items-center gap-1.5 rounded-md px-1.5 py-1 text-sm outline-hidden select-none focus:bg-accent focus:text-accent-foreground not-data-[variant=destructive]:not-data-[variant=warning]:focus:**:text-accent-foreground data-inset:pl-7 data-[variant=destructive]:text-destructive data-[variant=destructive]:focus:bg-destructive/10 data-[variant=destructive]:focus:text-destructive dark:data-[variant=destructive]:focus:bg-destructive/20 data-[variant=warning]:text-warning data-[variant=warning]:focus:bg-warning/10 data-[variant=warning]:focus:text-warning data-disabled:pointer-events-none data-disabled:opacity-50 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4 data-[variant=destructive]:*:[svg]:text-destructive data-[variant=warning]:*:[svg]:text-warning",
        size === "lg" && "gap-2 rounded-lg px-2 py-1.5",
        className
      )}
      {...props}
    />
  )
}

