function TraceCollapsible({
  className,
  ...props
}: Omit<React.ComponentProps<typeof Collapsible>, "open"> &
  (
    | { open?: undefined }
    | {
        open: boolean
        onOpenChange: NonNullable<
          React.ComponentProps<typeof Collapsible>["onOpenChange"]
        >
      }
  )) {
  return (
    <Collapsible
      data-slot="trace-collapsible"
      className={cn("flex w-full min-w-0 flex-col", className)}
      {...props}
    />
  )
}

function TraceCollapsibleTrigger({
  className,
  children,
  ...props
}: React.ComponentProps<typeof CollapsibleTrigger>) {
  return (
    <CollapsibleTrigger
      data-slot="trace-collapsible-trigger"
      className={cn(
        "group/trace-collapsible-trigger flex w-fit max-w-full min-w-0 cursor-pointer items-center gap-1 rounded-md text-left text-muted-foreground transition-colors outline-none hover:text-foreground focus-visible:ring-3 focus-visible:ring-ring/50 has-[[data-status=error]]:text-destructive",
        className
      )}
      {...props}
    >
      {children}
      <TraceIcon className="transition-transform group-aria-expanded/trace-collapsible-trigger:rotate-90">
        <ChevronRightIcon />
      </TraceIcon>
    </CollapsibleTrigger>
  )
}

function TraceCollapsibleContent({
  className,
  children,
  ...props
}: React.ComponentProps<typeof CollapsibleContent>) {
  return (
    <CollapsibleContent
      data-slot="trace-collapsible-content"
      /* 高度动画走 grid 轨道 0fr↔1fr（fr 可插值，无需测量）—— 此前
         h-(--collapsible-panel-height) 依赖 Base UI 首测高度，视口边缘条目
         被 content-visibility 跳过渲染时量到 10rem 估值，一行内容也按
         ~160px 展开动画再回落（闪烁/高度跳变的主源）。grid 子项必须
         min-h-0 + overflow-hidden 才能被轨道连续裁切；间距用 padding 不用
         margin —— margin 不随轨道裁切，收起后会残留空隙 */
      className="grid min-w-0 grid-rows-[0fr] transition-[grid-template-rows] duration-200 ease-out data-open:grid-rows-[1fr] data-starting-style:grid-rows-[0fr] data-ending-style:grid-rows-[0fr] motion-reduce:transition-none"
      {...props}
    >
      <div
        data-slot="trace-collapsible-content-inner"
        className={cn(
          /* 导线结构 = ml-7px（悬出）+ border-l + pl-4（文字缩进），内容缩进
             23px —— 与 live 过程流的导线容器（TurnGroup）逐像素同款，收尾
             翻折叠横向零位移。纵向间距 pt/pb 不用 mt/mb：margin 不随轨道
             裁切，收起后会残留空隙；横向 ml 不参与纵向裁切，安全 */
          "ml-[calc(--spacing(2)-1px)] min-h-0 min-w-0 overflow-hidden border-l pt-2 pb-1 pr-1 pl-4 leading-relaxed wrap-break-word text-muted-foreground",
          className
        )}
      >
        {children}
      </div>
    </CollapsibleContent>
  )
}

export {
  Trace,
  TraceLine,
  TraceIcon,
  TraceTitle,
  TraceDescription,
  TraceCollapsible,
  TraceCollapsibleTrigger,
  TraceCollapsibleContent,
}
