import { beforeEach, describe, expect, it } from 'vitest'
import { useWorkspaceStore } from '@/stores/workspace'
import type { FileDescriptor } from '@shared/files'

const scope = { sessionId: 'chat-a', refs: [] }
const descriptor = { fileId: 'file-a', serviceId: 'host', path: 'C:/project/a.ts', name: 'a.ts', kind: 'text', mime: 'text/plain', size: 3, version: '1', source: 'saved' } satisfies FileDescriptor
beforeEach(() => { useWorkspaceStore.getState().reset(); useWorkspaceStore.getState().setScope('chat-a') })
describe('多标签工作区', () => {
  it('文件树导航保留标签身份和顺序，不因同资源已在别页打开而归并当前实例', () => {
    const store = useWorkspaceStore.getState(), files = store.openFiles()
    const createdAt = useWorkspaceStore.getState().scopes['chat-a'].tabs[0].createdAt
    expect(store.navigateFile(files, { scope, target: './first.ts' })).toBe(true)
    expect(useWorkspaceStore.getState().scopes['chat-a'].tabs[0]).toMatchObject({ id: files, createdAt, kind: 'file', navigationMode: 'current' })
    const other = store.openFile({ scope, target: './other.ts' }, 'chat-a')
    store.identifyFile(other, 'other', descriptor)
    store.activate(files)
    store.navigateFile(files, { scope, target: './other.ts' })
    expect(store.identifyFile(files, 'other', descriptor)).toBe(files)
    expect(useWorkspaceStore.getState().scopes['chat-a'].tabs.map(tab => tab.id)).toEqual([files, other])
    expect(useWorkspaceStore.getState().scopes['chat-a'].activeId).toBe(files)
    expect(store.navigateFile('closed-tab', { scope, target: './late.ts' })).toBe(false)
    expect(useWorkspaceStore.getState().scopes['chat-a'].tabs).toHaveLength(2)
  })
  it('自动收起不改会话布局；显式展开接管自动状态', () => {
    const store = useWorkspaceStore.getState()
    const tab = store.openBrowser('https://kept.test')
    store.setLayout({ width: 530, expanded: true })
    const manual = useWorkspaceStore.getState().scopes['chat-a']
    store.setAutoCollapsed(true)
    expect(useWorkspaceStore.getState().scopes['chat-a']).toBe(manual)
    expect(useWorkspaceStore.getState().autoCollapsed).toBe(true)
    store.toggle()
    expect(useWorkspaceStore.getState().autoCollapsed).toBe(false)
    expect(useWorkspaceStore.getState().scopes['chat-a']).toMatchObject({ width: 530, expanded: true, collapsed: false, activeId: tab })
    store.setAutoCollapsed(true)
    store.setAutoCollapsed(false)
    expect(useWorkspaceStore.getState().scopes['chat-a'].collapsed).toBe(false)
    store.setLayout({ collapsed: true })
    store.setAutoCollapsed(true); store.setAutoCollapsed(false)
    expect(useWorkspaceStore.getState().scopes['chat-a'].collapsed).toBe(true)
  })
  it('前台打开资源可展开自动收起的面板，后台网页不能打破自动收起', () => {
    const store = useWorkspaceStore.getState()
    store.openBrowser('https://kept.test')
    store.setAutoCollapsed(true)
    store.openBrowser('https://background.test', undefined, 'chat-a', true)
    expect(useWorkspaceStore.getState().autoCollapsed).toBe(true)
    store.openFile({ scope, target: './a.ts' }, 'chat-a')
    expect(useWorkspaceStore.getState().autoCollapsed).toBe(false)
    store.setAutoCollapsed(true)
    store.openFile({ scope, target: './a.ts' }, 'chat-a')
    expect(useWorkspaceStore.getState().autoCollapsed).toBe(false)
  })
  it('启动功能替换空新页，同文件激活而不是重复创建', () => {
    const store = useWorkspaceStore.getState()
    store.newTab()
    const first = store.openFile({ scope, target: './a.ts' }, 'chat-a')
    const second = store.openFile({ scope, target: './a.ts' }, 'chat-a')
    expect(first).toBe(second)
    expect(useWorkspaceStore.getState().scopes['chat-a'].tabs).toHaveLength(1)
  })
  it('解析后不同别名归并到同一资源，后台关闭不改变正在看的标签', () => {
    const store = useWorkspaceStore.getState()
    const first = store.openFile({ scope, target: './a.ts' }, 'chat-a')
    store.identifyFile(first, 'real-a', descriptor)
    const alias = store.openFile({ scope, target: 'C:/project/a.ts' }, 'chat-a')
    expect(store.identifyFile(alias, 'real-a', descriptor)).toBe(first)
    const browser = store.openBrowser('https://example.com')
    store.remove(first)
    expect(useWorkspaceStore.getState().scopes['chat-a'].activeId).toBe(browser)
  })
  it('会话隔离、草稿绑定与排序保持原标签身份', () => {
    const store = useWorkspaceStore.getState()
    const draft = store.openBrowser('', undefined, 'draft:1')
    store.bindDraft('draft:1', 'chat-b')
    expect(useWorkspaceStore.getState().scopes['chat-b'].tabs[0]).toMatchObject({ id: draft, scopeId: 'chat-b' })
    expect(useWorkspaceStore.getState().scopes['draft:1']).toBeUndefined()
    store.setScope('chat-a')
    const a = store.newTab(), b = store.newTab()
    store.reorder('chat-a', [b, a])
    expect(useWorkspaceStore.getState().scopes['chat-a'].tabs.map(t => t.id)).toEqual([b, a])
    expect(useWorkspaceStore.getState().scopes['chat-b'].tabs[0].id).toBe(draft)
  })
  it('关闭最后一个标签能关完，重新展开才创建新页', () => {
    const store = useWorkspaceStore.getState(), id = store.newTab()
    store.remove(id)
    expect(useWorkspaceStore.getState().scopes['chat-a']).toMatchObject({ activeId: null, collapsed: true, tabs: [] })
    store.toggle()
    expect(useWorkspaceStore.getState().scopes['chat-a'].tabs).toHaveLength(1)
  })
  it('后台网页产生新标签不切会话工作区或改变活动页', () => {
    const store = useWorkspaceStore.getState()
    const original = store.openBrowser('https://a.test', undefined, 'chat-a')
    store.setScope('chat-b')
    const selected = store.newTab()
    store.openBrowser('https://b.test', undefined, 'chat-a', true)
    expect(useWorkspaceStore.getState().activeScopeId).toBe('chat-b')
    expect(useWorkspaceStore.getState().scopes['chat-b'].activeId).toBe(selected)
    expect(useWorkspaceStore.getState().scopes['chat-a'].activeId).toBe(original)
    expect(useWorkspaceStore.getState().scopes['chat-a'].tabs).toHaveLength(2)
  })
  it('恢复最后关闭的本地文件时重新授权，不使用已释放的context或父lease', () => {
    const store = useWorkspaceStore.getState()
    const id = store.openFile({ scope: { contextId: 'old-context', refs: [], relativeTo: 'old-lease', parentSource: { scope: { contextId: 'old-context', refs: [] }, target: 'C:/work/readme.md' } }, target: './child.md' }, 'chat-a')
    store.remove(id)
    const tab = store.reopen()
    expect(tab?.kind).toBe('file')
    if (tab?.kind !== 'file') throw new Error('未恢复文件')
    expect(tab.source.scope.contextId).toBe('restore')
    expect(tab.source.scope.relativeTo).toBeUndefined()
    expect(tab.source.scope.parentSource?.scope.contextId).toBe('restore')
  })
  it('隐私网页不进入最近关闭，普通网页恢复使用新实例身份', () => {
    const store = useWorkspaceStore.getState(), privateId = store.openBrowser('', 'private-1')
    store.remove(privateId)
    expect(useWorkspaceStore.getState().recent).toHaveLength(0)
    const original = store.openBrowser('https://example.com')
    store.remove(original)
    const restored = store.reopen()!
    expect(restored.id).not.toBe(original)
    expect(restored).toMatchObject({ kind: 'browser', url: 'https://example.com' })
  })
  it('已打开文件被规范化后，再次点击同一链接直接激活原标签不闪现重复页', () => {
    const store = useWorkspaceStore.getState()
    const source = { scope: { sessionId: 'chat-a', turnId: 'turn-1', refs: [] }, target: 'demo.js' }
    const id = store.openFile(source, 'chat-a')
    store.identifyFile(id, 'C:/Users/u/Desktop/demo.js', {
      fileId: 'f1', serviceId: 'svc', path: 'C:/Users/u/Desktop/demo.js', name: 'demo.js',
      kind: 'text', mime: 'text/javascript', size: 10, version: 'v1', source: 'current-workspace'
    })
    const secondId = store.openFile(source, 'chat-a')
    expect(secondId).toBe(id)
    expect(useWorkspaceStore.getState().scopes['chat-a'].tabs).toHaveLength(1)
  })
})
